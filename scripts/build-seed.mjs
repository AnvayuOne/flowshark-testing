// Builds db/seed.sql from testcases/flowshark.mjs
// Usage: node scripts/build-seed.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import modules from '../testcases/flowshark.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const TYPES = { F: 'Functional', V: 'Validation', UI: 'UI', N: 'Navigation', NEG: 'Negative', SEC: 'Security', E2E: 'End-to-End', DATA: 'Data Accuracy', AI: 'AI Behaviour' };
const PRI = { H: 'High', M: 'Medium', L: 'Low' };
const q = (v) => (v == null || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

let sql = `-- AUTO-GENERATED by scripts/build-seed.mjs from testcases/flowshark.mjs. Do not edit by hand.
-- Loaded by npm run db:setup. Safe to re-run: updates text, keeps status / notes / history.
begin;
`;
let total = 0;
const seen = new Set();

modules.forEach((m, mi) => {
  sql += `\n-- ${m.name}\ninsert into modules (code, name, description, sort_order) values (${q(m.code)}, ${q(m.name)}, ${q(m.desc)}, ${mi + 1})
on conflict (code) do update set name = excluded.name, description = excluded.description, sort_order = excluded.sort_order;\n`;
  const rows = m.cases.map((c, i) => {
    const [title, type, pri, steps, expected, pre] = c;
    if (!TYPES[type]) throw new Error(`${m.code} #${i + 1}: bad type ${type}`);
    if (!PRI[pri]) throw new Error(`${m.code} #${i + 1}: bad priority ${pri}`);
    if (!Array.isArray(steps) || steps.length === 0) throw new Error(`${m.code} #${i + 1}: no steps`);
    const code = `TC-${m.code}-${String(i + 1).padStart(3, '0')}`;
    if (seen.has(code)) throw new Error(`duplicate ${code}`);
    seen.add(code);
    total++;
    return `  (${q(code)}, ${q(title)}, ${q(TYPES[type])}, ${q(PRI[pri])}, ${q(pre ?? m.pre)}, ${q(JSON.stringify(steps))}::jsonb, ${q(expected)}, ${i + 1})`;
  });
  sql += `insert into test_cases (case_code, module_id, title, category, priority, preconditions, steps, expected_result, sort_order)
select v.case_code, (select id from modules where code = ${q(m.code)}), v.title, v.category, v.priority, v.preconditions, v.steps, v.expected_result, v.sort_order
from (values
${rows.join(',\n')}
) as v(case_code, title, category, priority, preconditions, steps, expected_result, sort_order)
on conflict (case_code) do update set
  module_id = excluded.module_id, title = excluded.title, category = excluded.category, priority = excluded.priority,
  preconditions = excluded.preconditions, steps = excluded.steps, expected_result = excluded.expected_result, sort_order = excluded.sort_order;\n`;
});

sql += '\ncommit;\n';
writeFileSync(join(root, 'db', 'seed.sql'), sql);
console.log(`seed.sql written: ${modules.length} modules, ${total} test cases`);
for (const m of modules) console.log(`  ${m.code.padEnd(7)} ${String(m.cases.length).padStart(3)}  ${m.name}`);
